// Copies the ABI and creation bytecode of CircuitWillEscrow and CircuitWillKey from the Foundry build output
// (contracts/out, produced by `forge build`) into frontend/artifacts.js. Run it after any contract change:
//   cd contracts; forge build; cd ../frontend; node scripts/build-artifacts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', '..', 'contracts', 'out');

function load(name) {
  const json = JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), 'utf8'));
  const bytecode = json.bytecode?.object;
  if (!bytecode || bytecode === '0x') throw new Error(`${name}: no bytecode in contracts/out; run forge build`);
  return { abi: json.abi, bytecode };
}

const escrow = load('CircuitWillEscrow');
const key = load('CircuitWillKey');

const body = `// GENERATED by frontend/scripts/build-artifacts.mjs from contracts/out (forge build). Do not edit by hand.
export const ESCROW_ABI = ${JSON.stringify(escrow.abi)};
export const ESCROW_BYTECODE = ${JSON.stringify(escrow.bytecode)};
export const KEY_ABI = ${JSON.stringify(key.abi)};
export const KEY_BYTECODE = ${JSON.stringify(key.bytecode)};
`;
writeFileSync(join(here, '..', 'artifacts.js'), body);
console.log(`artifacts.js written (escrow ${(escrow.bytecode.length - 2) / 2} bytes, key ${(key.bytecode.length - 2) / 2} bytes)`);
